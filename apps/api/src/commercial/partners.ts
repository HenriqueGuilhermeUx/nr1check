function slugCode(value: string) {
  const base = value.normalize("NFD").replace(/[\u0300-\u036f]/g, "").toUpperCase().replace(/[^A-Z0-9]/g, "").slice(0, 16) || "PARCEIRO";
  return base;
}

export async function approvePartner(partnerId: number, adminUserId: number) {
  await ready();
  const result = await db.execute(sql`
    update partner_profiles
    set status = 'active', approved_by = ${adminUserId}, approved_at = now(), updated_at = now()
    where id = ${partnerId}
    returning id, display_name
  `);
  const partner = rowsOf(result)[0];
  if (!partner) throw new TRPCError({ code: "NOT_FOUND", message: "Parceiro não encontrado" });

  const existing = await db.execute(sql`select code from partner_codes where partner_id = ${partnerId} and active = true limit 1`);
  if (rowsOf(existing)[0]) return { success: true, code: rowsOf(existing)[0].code as string };

  let code = slugCode(partner.display_name);
  for (let attempt = 0; attempt < 10; attempt++) {
    const candidate = attempt === 0 ? code : `${code}${Math.floor(10 + Math.random() * 90)}`;
    try {
      const inserted = await db.execute(sql`
        insert into partner_codes (partner_id, campaign_key, code)
        values (${partnerId}, ${PARTNER_CAMPAIGN_KEY}, ${candidate})
        returning code
      `);
      const row = rowsOf(inserted)[0];
      if (row) return { success: true, code: row.code as string };
    } catch {
      // tenta outro sufixo
    }
  }
  throw new TRPCError({ code: "INTERNAL_SERVER_ERROR", message: "Não foi possível gerar código único" });
}

export async function pausePartner(partnerId: number) {
  await ready();
  await db.execute(sql`update partner_profiles set status = 'paused', updated_at = now() where id = ${partnerId}`);
  await db.execute(sql`update partner_codes set active = false where partner_id = ${partnerId}`);
  return { success: true };
}

export async function listAdminCommissions() {
  await ready();
  const result = await db.execute(sql`
    select
      c.id, c.partner_id, c.payment_value_cents, c.commission_percent,
      c.commission_value_cents, c.status, c.eligible_at, c.paid_at, c.created_at,
      p.display_name as partner_name, p.payout_pix_key
    from partner_commissions c
    join partner_profiles p on p.id = c.partner_id
    where c.status in ('pending','approved')
    order by c.eligible_at asc
    limit 500
  `);
  return rowsOf(result);
}

export async function markCommissionPaid(commissionId: number) {
  await ready();
  const result = await db.execute(sql`
    update partner_commissions
    set status = 'paid', paid_at = now()
    where id = ${commissionId}
      and status in ('pending','approved')
      and eligible_at <= now()
    returning id
  `);
  if (!rowsOf(result).length) throw new TRPCError({ code: "BAD_REQUEST", message: "Comissão não está elegível para pagamento" });
  return { success: true };
}
