export async function partnerDashboard(userId: number) {
  await ready();
  const me = await partnerMe(userId);
  if (!me) throw new TRPCError({ code: "NOT_FOUND", message: "Perfil de parceiro não encontrado" });
  const partnerId = Number(me.id);
  const [clicks, referrals, commissions] = await Promise.all([
    db.execute(sql`select count(*)::int as count from partner_clicks where partner_id = ${partnerId}`),
    db.execute(sql`
      select count(*)::int as total,
             count(*) filter (where status = 'paid')::int as paid
      from partner_referrals where partner_id = ${partnerId}
    `),
    db.execute(sql`
      select
        coalesce(sum(commission_value_cents) filter (where status in ('pending','approved')),0)::int as pending_cents,
        coalesce(sum(commission_value_cents) filter (where status = 'paid'),0)::int as paid_cents,
        count(*)::int as count
      from partner_commissions where partner_id = ${partnerId}
    `),
  ]);
  return {
    profile: me,
    metrics: {
      clicks: Number(rowsOf(clicks)[0]?.count || 0),
      referrals: Number(rowsOf(referrals)[0]?.total || 0),
      paidCustomers: Number(rowsOf(referrals)[0]?.paid || 0),
      commissions: Number(rowsOf(commissions)[0]?.count || 0),
      pendingCents: Number(rowsOf(commissions)[0]?.pending_cents || 0),
      paidCents: Number(rowsOf(commissions)[0]?.paid_cents || 0),
    },
  };
}

