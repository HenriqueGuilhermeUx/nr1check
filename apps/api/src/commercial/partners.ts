async function ready() {
  await ensureCommercialSchema();
}

export function normalizePartnerCode(value: string) {
  return value.trim().toUpperCase().replace(/[^A-Z0-9_-]/g, "").slice(0, 40);
}

async function findActiveCode(code: string) {
  const normalized = normalizePartnerCode(code);
  if (!normalized) return null;
  const result = await db.execute(sql`
    select
      pc.id as code_id,
      pc.code,
      pc.partner_id,
      pc.campaign_key,
      pp.user_id as partner_user_id,
      pp.display_name,
      pp.partner_type,
      pp.commission_percent,
      pp.commission_months,
      c.name as campaign_name,
      c.plan_id,
      c.promo_amount_cents,
      c.regular_amount_cents,
      c.promo_months,
      c.max_redemptions,
      c.reserved_count,
      c.redeemed_count,
      c.active as campaign_active,
      c.starts_at,
      c.ends_at
    from partner_codes pc
    join partner_profiles pp on pp.id = pc.partner_id
    left join partner_campaigns c on c.key = pc.campaign_key
    where upper(pc.code) = ${normalized}
      and pc.active = true
      and pp.status = 'active'
    limit 1
  `);
  return rowsOf(result)[0] ?? null;
}

export async function publicPartnerOffer(code: string) {
  await ready();
  const row = await findActiveCode(code);
  if (!row) return null;
  const campaignActive =
    row.campaign_active === true &&
    new Date(row.starts_at).getTime() <= Date.now() &&
    (!row.ends_at || new Date(row.ends_at).getTime() > Date.now());
  const remaining = Math.max(0, Number(row.max_redemptions ?? 0) - Number(row.reserved_count ?? 0));
  return {
    code: row.code as string,
    partnerName: row.display_name as string,
    partnerType: row.partner_type as string,
    commissionPercent: Number(row.commission_percent),
    campaign: row.campaign_key ? {
      key: row.campaign_key as string,
      name: row.campaign_name as string,
      planId: row.plan_id as string,
      promoAmountCents: Number(row.promo_amount_cents),
      regularAmountCents: Number(row.regular_amount_cents),
      promoMonths: Number(row.promo_months),
      maxRedemptions: Number(row.max_redemptions),
      remaining,
      active: campaignActive && remaining > 0,
    } : null,
  };
}

export async function trackPartnerClick(code: string, visitorId: string, referrer?: string | null) {
  await ready();
  const row = await findActiveCode(code);
  if (!row) return { tracked: false };
  await db.execute(sql`
    insert into partner_clicks (partner_id, code_id, visitor_id, referrer)
    values (${Number(row.partner_id)}, ${Number(row.code_id)}, ${visitorId.slice(0, 120)}, ${referrer?.slice(0, 1000) ?? null})
    on conflict (code_id, visitor_id) do nothing
  `);
  return { tracked: true, code: row.code as string };
}

export async function claimPartnerReferral(userId: number, code: string) {
  await ready();
  const row = await findActiveCode(code);
  if (!row) throw new TRPCError({ code: "NOT_FOUND", message: "Código de parceiro inválido ou inativo" });
  if (Number(row.partner_user_id) === userId) {
    throw new TRPCError({ code: "BAD_REQUEST", message: "Autoindicação não é permitida" });
  }

  const existing = await db.execute(sql`
    select id, partner_id, code_id from partner_referrals where user_id = ${userId} limit 1
  `);
  const current = rowsOf(existing)[0];
  if (current) return { claimed: true, immutable: true, referralId: Number(current.id) };

  const inserted = await db.execute(sql`
    insert into partner_referrals (partner_id, code_id, user_id, campaign_key)
    values (${Number(row.partner_id)}, ${Number(row.code_id)}, ${userId}, ${row.campaign_key ?? null})
    on conflict (user_id) do nothing
    returning id
  `);
  const created = rowsOf(inserted)[0];
  return { claimed: Boolean(created), immutable: false, referralId: created ? Number(created.id) : null };
}

export async function reservePartnerOffer(userId: number, planId: string) {
  await ready();
  const referralResult = await db.execute(sql`
    select
      r.*,
      p.status as partner_status,
      p.commission_percent,
      p.commission_months,
      c.plan_id,
      c.promo_amount_cents,
      c.regular_amount_cents,
      c.promo_months,
      c.max_redemptions,
      c.reserved_count,
      c.active as campaign_active,
      c.starts_at,
      c.ends_at
    from partner_referrals r
    join partner_profiles p on p.id = r.partner_id
    left join partner_campaigns c on c.key = r.campaign_key
    where r.user_id = ${userId}
    limit 1
  `);
  let referral = rowsOf(referralResult)[0];
  if (!referral || referral.partner_status !== "active") return null;

  const campaignEligible =
    referral.campaign_key &&
    referral.campaign_active === true &&
    referral.plan_id === planId &&
    new Date(referral.starts_at).getTime() <= Date.now() &&
    (!referral.ends_at || new Date(referral.ends_at).getTime() > Date.now());

  if (!referral.promo_reserved && campaignEligible) {
    const capacity = await db.execute(sql`
      update partner_campaigns
      set reserved_count = reserved_count + 1, updated_at = now()
      where key = ${referral.campaign_key}
        and active = true
        and reserved_count < max_redemptions
      returning promo_amount_cents, regular_amount_cents, promo_months
    `);
    const reserved = rowsOf(capacity)[0];
    if (reserved) {
      await db.execute(sql`
        update partner_referrals
        set
          promo_reserved = true,
          promo_amount_cents = ${Number(reserved.promo_amount_cents)},
          regular_amount_cents = ${Number(reserved.regular_amount_cents)},
          reserved_at = now(),
          updated_at = now()
        where id = ${Number(referral.id)}
      `);
      referral = {
        ...referral,
        promo_reserved: true,
        promo_amount_cents: Number(reserved.promo_amount_cents),
        regular_amount_cents: Number(reserved.regular_amount_cents),
      };
    }
  }

  let promoActive = referral.promo_reserved === true && planId === referral.plan_id;
  if (promoActive && referral.first_paid_at) {
    const promoUntil = new Date(referral.first_paid_at);
    promoUntil.setMonth(promoUntil.getMonth() + Number(referral.promo_months || 12));
    promoActive = Date.now() < promoUntil.getTime();
  }

  return {
    referralId: Number(referral.id),
    partnerId: Number(referral.partner_id),
    promoApplied: promoActive,
    promoAmountCents: promoActive ? Number(referral.promo_amount_cents) : null,
    regularAmountCents: Number(referral.regular_amount_cents || 0) || null,
    commissionPercent: Number(referral.commission_percent),
    commissionMonths: Number(referral.commission_months),
  };
}

export async function recordPartnerCommission(paymentId: number) {
  await ready();
  const result = await db.execute(sql`
    select
      bp.id as payment_id,
      bp.user_id,
      bp.amount_cents,
      bp.partner_referral_id,
      r.id as referral_id,
      r.partner_id,
      r.campaign_key,
      r.first_paid_at,
      r.redeemed_at,
      p.commission_percent,
      p.commission_months,
      p.status as partner_status
    from billing_payments bp
    join partner_referrals r on r.id = bp.partner_referral_id
    join partner_profiles p on p.id = r.partner_id
    where bp.id = ${paymentId}
    limit 1
  `);
  const row = rowsOf(result)[0];
  if (!row || row.partner_status !== "active") return;

  const firstPaidAt = row.first_paid_at ? new Date(row.first_paid_at) : new Date();
  const commissionUntil = new Date(firstPaidAt);
  commissionUntil.setMonth(commissionUntil.getMonth() + Number(row.commission_months || 12));
  if (Date.now() >= commissionUntil.getTime()) return;

  const commissionValue = Math.round(Number(row.amount_cents) * Number(row.commission_percent) / 100);
  await db.execute(sql`
    insert into partner_commissions (
      partner_id, referral_id, user_id, payment_id,
      payment_value_cents, commission_percent, commission_value_cents
    )
    values (
      ${Number(row.partner_id)}, ${Number(row.referral_id)}, ${Number(row.user_id)}, ${paymentId},
      ${Number(row.amount_cents)}, ${Number(row.commission_percent)}, ${commissionValue}
    )
    on conflict (payment_id) do nothing
  `);

  await db.execute(sql`
    update partner_referrals
    set
      status = 'paid',
      first_paid_at = coalesce(first_paid_at, now()),
      last_paid_at = now(),
      updated_at = now()
    where id = ${Number(row.referral_id)}
  `);

  if (!row.redeemed_at && row.campaign_key) {
    const redeemed = await db.execute(sql`
      update partner_referrals
      set redeemed_at = now(), updated_at = now()
      where id = ${Number(row.referral_id)}
        and redeemed_at is null
      returning id
    `);
    if (rowsOf(redeemed).length) {
      await db.execute(sql`
        update partner_campaigns
        set redeemed_count = redeemed_count + 1, updated_at = now()
        where key = ${row.campaign_key}
      `);
    }
  }
}

export async function extendBillingPeriod(input: { scope: "company" | "accountant"; userId: number; companyId?: number | null; paymentId: number; planId: string }) {
  await ready();
  const periodStart = new Date();
  let result: any;
  if (input.scope === "company" && input.companyId) {
    result = await db.execute(sql`
      update companies
      set
        billing_provider = 'woovi',
        billing_plan = ${input.planId},
        billing_status = 'active',
        billing_period_end = greatest(coalesce(billing_period_end, now()), now()) + interval '1 month',
        updated_at = now()
      where id = ${input.companyId}
      returning billing_period_end
    `);
  } else {
    result = await db.execute(sql`
      update users
      set
        billing_provider = 'woovi',
        billing_plan = ${input.planId},
        billing_status = 'active',
        billing_period_end = greatest(coalesce(billing_period_end, now()), now()) + interval '1 month',
        updated_at = now()
      where id = ${input.userId}
      returning billing_period_end
    `);
  }
  const periodEnd = rowsOf(result)[0]?.billing_period_end ?? null;
  await db.execute(sql`
    update billing_payments
    set access_period_start = ${periodStart}, access_period_end = ${periodEnd}, updated_at = now()
    where id = ${input.paymentId}
  `);
  return periodEnd;
}

